        await ev(`const modal=document.createElement('div');modal.id='modal';modal.style.cssText='position:fixed;inset:0;background:rgba(0,0,0,.5);z-index:20';modal.innerHTML='<div id="modal-scroll" style="position:absolute;left:300px;top:50px;width:200px;height:200px;overflow:auto;background:#777"><div style="height:800px;width:600px">Modal</div></div>';document.body.appendChild(modal)`);
