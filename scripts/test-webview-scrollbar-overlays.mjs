// Optional real-browser regression suite. Requires Node.js 22+ and an installed Chromium browser.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
if (typeof WebSocket !== 'function')
    throw new Error('Browser scrollbar tests require Node.js 22 or newer.');
const chromePaths = [process.env.CHROME_PATH,
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium', '/usr/bin/chromium-browser'];
const chromePath = chromePaths.find(candidate => candidate && fs.existsSync(candidate));
